/**
 * Translates common gender strings into pure Hindi if needed.
 */
export function translateGender(gender?: string | null, lang: PdfLanguage = "en"): string {
  if (!gender) return "—";
  const g = gender.toLowerCase().trim();
  if (lang === "hi") {
    if (g === "male" || g === "m") return "पुरुष";
    if (g === "female" || g === "f") return "महिला";
    if (g === "other" || g === "o") return "अन्य";
  }
  return gender.charAt(0).toUpperCase() + gender.slice(1);
}

/**
 * Translates age string into Hindi if needed.
 */
export function translateAge(age?: string | null, lang: PdfLanguage = "en"): string {
  if (!age) return "—";
  if (lang !== "hi") return age;
  return age
    .replace(/\b(\d+)\s*(?:yrs|years|y|वर्ष)\b/gi, "$1 वर्ष")
    .replace(/\b(\d+)\s*(?:months|month|m|माह)\b/gi, "$1 माह")
    .replace(/\b(\d+)\s*(?:days|day|d|दिन)\b/gi, "$1 दिन")
    .replace(/\b(\d+)\s*$/g, "$1 वर्ष");
}

