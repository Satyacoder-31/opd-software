/**
 * Translates common medical frequency codes into pure Hindi.
 */
export function translateFrequency(freq?: string | null, lang: PdfLanguage = "en"): string {
  if (!freq) return "—";
  if (lang !== "hi") return freq;

  const f = freq.trim();
  if (f === "1-0-1") return "सुबह 1 - रात 1 (दिन में दो बार)";
  if (f === "1-0-0") return "सुबह 1 (दिन में एक बार)";
  if (f === "0-0-1") return "रात 1 (सोते समय)";
  if (f === "0-1-0") return "दोपहर 1";
  if (f === "1-1-1") return "सुबह 1 - दोपहर 1 - रात 1 (दिन में तीन बार)";
  if (f === "1-1-0") return "सुबह 1 - दोपहर 1";
  if (f === "0-1-1") return "दोपहर 1 - रात 1";
  if (f === "1-1-1-1") return "दिन में 4 बार (हर 6 घंटे में)";
  if (/^once daily|^\bod\b/i.test(f)) return "दिन में एक बार";
  if (/^twice daily|^\bbd\b|^\bbid\b/i.test(f)) return "दिन में दो बार";
  if (/^thrice daily|^three times daily|^\btds\b|^\btid\b/i.test(f)) return "दिन में तीन बार";
  if (/^four times daily|^\bqid\b/i.test(f)) return "दिन में चार बार";
  if (/as needed|sos|prn/i.test(f)) return "आवश्यकता पड़ने पर (दर्द होने पर)";
  if (/bedtime|at night|at bedtime|hs/i.test(f)) return "रात को सोते समय";
  if (/alternate days?|every alternate day/i.test(f)) return "एक दिन छोड़कर";
  if (/once weekly|weekly/i.test(f)) return "सप्ताह में एक बार";
  return f;
}

