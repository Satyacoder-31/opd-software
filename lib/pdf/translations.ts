/**
 * Translates medicine duration into pure Hindi.
 */
export function translateDuration(duration?: string | null, lang: PdfLanguage = "en"): string {
  if (!duration) return "—";
  if (lang !== "hi") return duration;

  const d = duration.trim();
  const daysMatch = d.match(/^(\d+)\s*(?:days?|d|दिन)?$/i);
  if (daysMatch) return `${daysMatch[1]} दिन`;

  const weeksMatch = d.match(/^(\d+)\s*(?:weeks?|w|सप्ताह)?$/i);
  if (weeksMatch) return `${weeksMatch[1]} सप्ताह`;

  const monthsMatch = d.match(/^(\d+)\s*(?:months?|m|माह|महीना)?$/i);
  if (monthsMatch) return `${monthsMatch[1]} महीना`;

  if (/ongoing|continue|regular/i.test(d)) return "लगातार जारी रखें";
  if (/as directed/i.test(d)) return "निर्देशानुसार";

  return d
    .replace(/\bdays?\b/gi, "दिन")
    .replace(/\bweeks?\b/gi, "सप्ताह")
    .replace(/\bmonths?\b/gi, "महीना");
}

