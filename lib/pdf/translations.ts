  if (c.includes("neck pain")) return "गर्दन में दर्द व अकड़न";
  if (c.includes("joint stiffness")) return "जोड़ों में अकड़न व जकड़न";
  if (c.includes("swelling")) return "जोड़ों में सूजन एवं दर्द";
  if (c.includes("difficulty walking")) return "चलने-फिरने में कठिनाई";
  if (c.includes("climbing stairs")) return "सीढ़ियां चढ़ने-उतरने में तेज दर्द";
  if (c.includes("heel pain")) return "सुबह उठने पर एड़ी में तेज दर्द";
